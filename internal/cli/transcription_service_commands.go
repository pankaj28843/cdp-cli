func (a *app) newTranscriptionServiceCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "service",
		Short: "Install and control the transcription API service",
		Long: "Manage cdp transcription serve as a native service. macOS uses a LaunchAgent; " +
			"Linux uses systemd --user by default or a machine-wide systemd unit with --system. " +
			"The service reads its configuration from environment values generated by install. " +
			"Service-manager diagnostics are bounded and canceled within the owned process group.",
		Example: "  cdp transcription service install --address '[::]:28765'\n" +
			"  cdp transcription service install --system --address '0.0.0.0:28765'\n" +
			"  cdp transcription service status\n" +
			"  cdp transcription service uninstall",
	}
	cmd.PersistentFlags().Bool("system", false, "use the machine-wide Linux systemd service (requires root)")
	cmd.AddCommand(a.newTranscriptionServiceInstallCommand())
	cmd.AddCommand(a.newTranscriptionServiceStartCommand("start", "Start and enable the transcription API service"))
	cmd.AddCommand(a.newTranscriptionServiceStartCommand("restart", "Restart the transcription API service"))
	cmd.AddCommand(a.newTranscriptionServiceStopCommand())
	cmd.AddCommand(a.newTranscriptionServiceStatusCommand())
	cmd.AddCommand(a.newTranscriptionServiceUninstallCommand())
	return cmd
}

func (a *app) newTranscriptionServiceInstallCommand() *cobra.Command {
	var address string
	var httpAddress string
	var provider string
	var allowedProviders []string
	var localBaseURL string
	var localRealtimeBaseURL string
	var localAPIKey string
	var maxAudioBytes int64
	var authRefreshInterval time.Duration
	var authRefreshOffset time.Duration
	var fixtureDir string
	var probeInterval time.Duration
	var persistAudio bool
	var tlsCertFile string
	var tlsKeyFile string
	var tlsSelfSigned bool
	var tlsHosts []string
	var tlsRegenerate bool
	var binaryPath string
	var start bool
	cmd := &cobra.Command{
		Use:   "install",
		Short: "Write the native service and start it",
		Long: "Write a LaunchAgent plist on macOS or a systemd unit plus owner-only " +
			"environment file on Linux. Use --system for a machine-wide service; it requires root " +
			"and starts the unauthenticated service by default.",
		Example: "  cdp transcription service install --address '[::]:28765' --http-address '[::]:28766' --start\n" +
			"  cdp transcription service install --address '[::]:28765' --http-address '[::]:28766' --tls-self-signed --tls-host 192.168.5.249",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			systemScope, err := cmd.Flags().GetBool("system")
			if err != nil {
				return err
			}
			fixtureDir = strings.TrimSpace(fixtureDir)
			fixtureCount := 0
			if fixtureDir != "" {
				if _, err := transcriptionapi.LoadFixtureCatalog(fixtureDir); err != nil {
					return fmt.Errorf("validate transcription service fixture corpus: %w", err)
				}
				fixtureCount = transcriptionapi.DefaultFixtureCount
			}
			if authRefreshOffset < 0 || (authRefreshInterval == 0 && authRefreshOffset != 0) || (authRefreshInterval > 0 && authRefreshOffset >= authRefreshInterval) {
				return fmt.Errorf("--auth-refresh-offset must be non-negative and shorter than its interval")
			}
			if probeInterval == 0 {
				probeInterval = transcriptionapi.DefaultProbeInterval
			}
			authRefreshEnabled := authRefreshInterval > 0
			platform, paths, config, err := a.transcriptionServiceConfig(systemScope, binaryPath, address, httpAddress, provider, allowedProviders, localBaseURL, localRealtimeBaseURL, localAPIKey, maxAudioBytes, authRefreshInterval, authRefreshOffset, authRefreshEnabled, fixtureDir, probeInterval, persistAudio, tlsCertFile, tlsKeyFile)
			if err != nil {
				return err
			}
			if systemScope {
				if err := validateSystemServiceAccount(); err != nil {
					return err
				}
			}
			if err := os.MkdirAll(config.StateDir, 0o700); err != nil {
				return fmt.Errorf("create transcription service state directory: %w", err)
			}
			tlsFiles, err := configureTranscriptionTLS(config.StateDir, config.TLSCertFile, config.TLSKeyFile, tlsSelfSigned, tlsHosts, tlsRegenerate)
			if err != nil {
				return err
			}
			config.TLSCertFile = tlsFiles.CertFile
			config.TLSKeyFile = tlsFiles.KeyFile
			artifacts, err := transcriptionservice.Render(platform, config, paths)
			if err != nil {
				return err
			}
			if err := writeTranscriptionServiceArtifacts(artifacts, paths.LogDirectory); err != nil {
				return err
			}
			if systemScope {
				if err := prepareSystemServiceOwnership(config.StateDir, paths); err != nil {
					return err
				}
			}
			if start {
				if _, err := runTranscriptionServiceAction(cmd.Context(), platform, "restart", paths); err != nil {
					return err
				}
			}
			return a.render(cmd.Context(), "transcription service installed", map[string]any{
				"platform":             platform,
				"service":              serviceName(platform),
				"started":              start,
				"address":              config.Address,
				"http_address":         config.HTTPAddress,
				"provider":             config.Provider,
				"auth_refresh_enabled": authRefreshEnabled,
				"auth_refresh_offset":  authRefreshOffset.String(),
				"probe_interval":       config.ProbeInterval.String(),
				"fixture_count":        fixtureCount,
				"audio_persisted":      config.PersistAudio,
				"tls_enabled":          strings.TrimSpace(config.TLSCertFile) != "",
				"tls_cert_file":        tlsFiles.CertFile,
				"tls_hosts":            tlsFiles.Hosts,
				"tls_reused":           tlsFiles.Reused,
				"demo_url":             preferredDemoURL(config.Address, strings.TrimSpace(config.TLSCertFile) != "", tlsFiles.Hosts),
				"demo_urls":            demoURLs(config.Address, strings.TrimSpace(config.TLSCertFile) != "", tlsFiles.Hosts),
				"artifacts":            artifactPaths(artifacts),
			})
		},
	}
	cmd.Flags().StringVar(&address, "address", envDefault("CDP_TRANSCRIPTION_ADDRESS", transcriptionapi.DefaultListenAddress), "primary listen address; defaults to [::]:28765 (dual-stack wildcard where IPv6 is enabled)")
	cmd.Flags().StringVar(&httpAddress, "http-address", envDefault("CDP_TRANSCRIPTION_HTTP_ADDRESS", transcriptionapi.DefaultHTTPListenAddress), "cleartext companion listen address; defaults to [::]:28766 (dual-stack wildcard where IPv6 is enabled)")
	cmd.Flags().StringVar(&provider, "default-provider", envDefault("CDP_TRANSCRIPTION_PROVIDER", string(transcriptionapi.ProviderLocal)), "default provider: local, bing-web, chatgpt-web, claude-web, gemini-web, or microsoft-365-web")
	cmd.Flags().StringSliceVar(&allowedProviders, "providers", envStringSlice("CDP_TRANSCRIPTION_PROVIDERS"), "provider allowlist persisted into the user service; repeat or comma-separate")
	cmd.Flags().StringVar(&localBaseURL, "local-base-url", os.Getenv("CDP_TRANSCRIPTION_LOCAL_BASE_URL"), "local OpenAI-compatible provider base URL, usually ending in /v1")
	cmd.Flags().StringVar(&localRealtimeBaseURL, "local-realtime-base-url", os.Getenv("CDP_TRANSCRIPTION_LOCAL_REALTIME_BASE_URL"), "optional local realtime provider base URL, usually ending in /v1")
	cmd.Flags().StringVar(&localAPIKey, "local-api-key", os.Getenv("CDP_TRANSCRIPTION_LOCAL_API_KEY"), "API key for the configured local provider")
	cmd.Flags().Int64Var(&maxAudioBytes, "max-audio-bytes", envInt64("CDP_TRANSCRIPTION_MAX_AUDIO_BYTES", transcriptionapi.DefaultMaxAudioBytes), "maximum retained audio-cache bytes")
	cmd.Flags().DurationVar(&authRefreshInterval, "auth-refresh-interval", envDuration("CDP_TRANSCRIPTION_AUTH_REFRESH_INTERVAL", transcriptionapi.DefaultAuthRefreshInterval), "shared recurring freshness check for all online providers; use 0s to disable")
	cmd.Flags().DurationVar(&authRefreshOffset, "auth-refresh-offset", envDuration("CDP_TRANSCRIPTION_AUTH_REFRESH_OFFSET", 0), "wall-clock phase offset for recurring auth refreshes; must be shorter than the interval")
	cmd.Flags().StringVar(&fixtureDir, "fixture-dir", envDefault("CDP_TRANSCRIPTION_FIXTURE_DIR", defaultTranscriptionFixtureDir()), "checked-in WebM corpus used by the bounded provider health probe; explicitly empty disables scheduled probes")
	cmd.Flags().DurationVar(&probeInterval, "probe-interval", envDuration("CDP_TRANSCRIPTION_PROBE_INTERVAL", transcriptionapi.DefaultProbeInterval), "interval between bounded synthetic provider health probes")
	cmd.Flags().BoolVar(&persistAudio, "persist-audio", envBool("CDP_TRANSCRIPTION_PERSIST_AUDIO"), "retain uploaded audio under the state directory; default is ephemeral transaction media")
	cmd.Flags().StringVar(&tlsCertFile, "tls-cert", os.Getenv("CDP_TRANSCRIPTION_TLS_CERT"), "TLS certificate file; provide with --tls-key for HTTPS microphone access over LAN")
	cmd.Flags().StringVar(&tlsKeyFile, "tls-key", os.Getenv("CDP_TRANSCRIPTION_TLS_KEY"), "TLS private key file; provide with --tls-cert")
	cmd.Flags().BoolVar(&tlsSelfSigned, "tls-self-signed", false, "generate or reuse a private-LAN self-signed certificate under the cdp state directory")
	cmd.Flags().StringSliceVar(&tlsHosts, "tls-host", nil, "DNS name or IP to include in a self-signed certificate; repeat for multiple names")
	cmd.Flags().BoolVar(&tlsRegenerate, "tls-regenerate", false, "replace the generated self-signed certificate and key")
	cmd.Flags().StringVar(&binaryPath, "binary", "", "absolute cdp binary path; defaults to the running executable")
	cmd.Flags().BoolVar(&start, "start", true, "start and enable the service after installing its files")
	return cmd
}

